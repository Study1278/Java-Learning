package Inheritance;

public class Demo {
    public static void main(String args[]){
        ScientificCalc Cal = new ScientificCalc();
        System.out.println(Cal.Add(10,2));
        System.out.println(Cal.Sub(10,2));
        System.out.println(Cal.multi(10,2));
        System.out.println(Cal.divi(10,2));
        System.out.println(Cal.power(2,4));
    }
}